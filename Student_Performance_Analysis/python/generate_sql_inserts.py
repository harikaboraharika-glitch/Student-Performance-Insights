"""
generate_sql_inserts.py
-----------------------
Reads the cleaned star-schema CSVs created by analysis.py and writes sql/insert_data.sql
(INSERT statements for students, subjects and performance).

Run AFTER analysis.py:   python python/generate_sql_inserts.py
"""
from pathlib import Path
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
P = ROOT / "data" / "processed"
OUT = ROOT / "sql" / "insert_data.sql"
BATCH = 100


def q(v):
    """Format a Python value as a SQL literal."""
    return f"'{v}'" if isinstance(v, str) else str(v)


def write_inserts(f, table, df):
    # Map CSV headers -> MySQL column names (explicit, so schema and inserts always match)
    rename = {"Class": "class_name", "Pass_Fail": "pass_status"}
    cols = ", ".join(rename.get(c, c.lower()) for c in df.columns)
    for i in range(0, len(df), BATCH):
        chunk = df.iloc[i:i + BATCH]
        values = ",\n    ".join("(" + ", ".join(q(v) for v in row) + ")" for row in chunk.itertuples(index=False))
        f.write(f"INSERT INTO {table} ({cols}) VALUES\n    {values};\n\n")


students = pd.read_csv(P / "dim_students.csv")
subjects = pd.read_csv(P / "dim_subjects.csv")
fact = pd.read_csv(P / "fact_performance.csv")

with open(OUT, "w") as f:
    f.write("""-- ============================================================================
-- insert_data.sql   (auto-generated by python/generate_sql_inserts.py)
-- Loads the CLEANED dataset into students, subjects and performance.
--
-- OPTION A (simplest): run this script as-is -> it contains every INSERT statement.
--
-- OPTION B (CSV import): skip this file and load the CSVs in data/processed/ instead:
--   1) Enable local infile once:   SET GLOBAL local_infile = 1;
--      (start the client with:     mysql --local-infile=1 -u root -p)
--   2) Run, adjusting the path to your machine (use forward slashes on Windows):
--
--   LOAD DATA LOCAL INFILE 'C:/path/Student_Performance_Analysis/data/processed/dim_students.csv'
--   INTO TABLE students FIELDS TERMINATED BY ',' ENCLOSED BY '"'
--   LINES TERMINATED BY '\\n' IGNORE 1 ROWS (student_id, gender, age, class_name);
--
--   LOAD DATA LOCAL INFILE 'C:/path/Student_Performance_Analysis/data/processed/dim_subjects.csv'
--   INTO TABLE subjects FIELDS TERMINATED BY ',' ENCLOSED BY '"'
--   LINES TERMINATED BY '\\n' IGNORE 1 ROWS (subject_id, subject_name);
--
--   LOAD DATA LOCAL INFILE 'C:/path/Student_Performance_Analysis/data/processed/fact_performance.csv'
--   INTO TABLE performance FIELDS TERMINATED BY ',' ENCLOSED BY '"'
--   LINES TERMINATED BY '\\n' IGNORE 1 ROWS
--   (performance_id, student_id, subject_id, attendance, study_hours, assignment_marks,
--    exam_marks, final_marks, grade, pass_status);
--
--   (MySQL Workbench alternative: right-click table > Table Data Import Wizard > choose CSV.)
-- ============================================================================
USE student_performance_db;

""")
    f.write("-- ---------- subjects ----------\n")
    write_inserts(f, "subjects", subjects)
    f.write("-- ---------- students ----------\n")
    write_inserts(f, "students", students)
    f.write("-- ---------- performance ----------\n")
    write_inserts(f, "performance", fact)
    f.write("-- Quick check\nSELECT (SELECT COUNT(*) FROM students) AS students,\n"
            "       (SELECT COUNT(*) FROM subjects) AS subjects,\n"
            "       (SELECT COUNT(*) FROM performance) AS performance_rows;\n")
print(f"Wrote {OUT}  (students={len(students)}, subjects={len(subjects)}, performance={len(fact)})")
